"""Column profiling of warehouse tables.

Profiling comes *before* cleaning rules: you cannot write a rule for data you have not
looked at. For every column we compute exact statistics (DuckDB's ``SUMMARIZE`` is
faster but its distinct count is an HyperLogLog *approximation*; it reported more
distinct ids than rows on our data).

Load-metadata columns (``_loaded_at`` …) are excluded so that the report only changes
when the data changes, not on every run.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path

import duckdb
import pandas as pd

logger = logging.getLogger(__name__)

NUMERIC_TYPES = ("BIGINT", "INTEGER", "DOUBLE", "FLOAT", "DECIMAL", "HUGEINT", "SMALLINT")


@dataclass(frozen=True)
class TableProfile:
    table: str
    rows: int
    duplicate_rows: int
    columns: pd.DataFrame  # one row per column


def _columns(con: duckdb.DuckDBPyConnection, table: str) -> list[tuple[str, str]]:
    schema, name = table.split(".")
    return con.execute(
        "select column_name, data_type from information_schema.columns "
        "where table_schema = ? and table_name = ? order by ordinal_position",
        [schema, name],
    ).fetchall()


def _profile_column(
    con: duckdb.DuckDBPyConnection, table: str, column: str, dtype: str, rows: int
) -> dict:
    q = f'"{column}"'
    base = con.execute(
        f"select count({q}), count(distinct {q}), min({q})::varchar, max({q})::varchar from {table}"
    ).fetchone()
    non_null, distinct, min_v, max_v = base
    out = {
        "column": column,
        "type": dtype,
        "non_null": non_null,
        "pct_null": round(100 * (rows - non_null) / rows, 2) if rows else 0.0,
        "distinct": distinct,
        "pct_unique": round(100 * distinct / non_null, 2) if non_null else 0.0,
        "min": min_v,
        "max": max_v,
        "mean": None,
        "std": None,
        "median": None,
        "top_values": "",
    }
    if dtype.startswith(NUMERIC_TYPES):
        mean, std, median = con.execute(
            f"select avg({q}), stddev_samp({q}), median({q}) from {table}"
        ).fetchone()
        out.update(
            mean=None if mean is None else round(mean, 3),
            std=None if std is None else round(std, 3),
            median=median,
        )
    if dtype == "VARCHAR" and distinct <= 50:
        top = con.execute(
            f"select {q}, count(*) as n from {table} where {q} is not null "
            f"group by 1 order by n desc, 1 limit 5"
        ).fetchall()
        out["top_values"] = ", ".join(f"`{v}` ({n})" for v, n in top)
    return out


def profile_table(con: duckdb.DuckDBPyConnection, table: str) -> TableProfile:
    """Exact per-column profile of ``schema.table`` (metadata columns ``_*`` excluded)."""
    cols = [(c, t) for c, t in _columns(con, table) if not c.startswith("_")]
    if not cols:
        raise ValueError(f"table {table} not found or has no columns")
    rows = con.execute(f"select count(*) from {table}").fetchone()[0]
    names = ", ".join(f'"{c}"' for c, _ in cols)
    distinct_rows = con.execute(f"select count(*) from (select distinct {names} from {table})")
    duplicate_rows = rows - distinct_rows.fetchone()[0]
    profiles = [_profile_column(con, table, c, t, rows) for c, t in cols]
    return TableProfile(table, rows, duplicate_rows, pd.DataFrame(profiles))


def _cell(value: object) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return ""
    return str(value).replace("|", "\\|")


def to_markdown(profile: TableProfile) -> str:
    lines = [
        f"# Profile — `{profile.table}`",
        "",
        "> Generated by `lead-funnel profile`. Exact statistics; load-metadata columns excluded.",
        "",
        f"- **Rows:** {profile.rows:,}",
        f"- **Fully duplicated rows:** {profile.duplicate_rows:,}",
        "",
        "| Column | Type | % null | Distinct | % unique | Min | Max | Mean | Std | Median |",
        "|---|---|---:|---:|---:|---|---|---:|---:|---:|",
    ]
    for r in profile.columns.itertuples(index=False):
        lines.append(
            f"| `{r.column}` | {r.type} | {r.pct_null} | {r.distinct:,} | {r.pct_unique} | "
            f"{_cell(r.min)} | {_cell(r.max)} | {_cell(r.mean)} | {_cell(r.std)} | "
            f"{_cell(r.median)} |"
        )
    tops = [r for r in profile.columns.itertuples(index=False) if r.top_values]
    if tops:
        lines += ["", "## Most frequent values (low-cardinality text columns)", ""]
        lines += [f"- `{r.column}`: {r.top_values}" for r in tops]
    return "\n".join(lines) + "\n"


def write_profiles(con: duckdb.DuckDBPyConnection, tables: list[str], out_dir: Path) -> list[Path]:
    """Profile each table and write ``<out_dir>/profile_<table>.md``."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for table in tables:
        path = out_dir / f"profile_{table.split('.')[1]}.md"
        path.write_text(to_markdown(profile_table(con, table)), encoding="utf-8", newline="\n")
        logger.info("Wrote %s", path)
        written.append(path)
    return written

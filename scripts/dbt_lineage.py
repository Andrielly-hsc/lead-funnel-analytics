"""Render the dbt lineage graph as a Mermaid diagram in docs/lineage.md.

Usage (after any dbt command that writes dbt/target/manifest.json):

    python scripts/dbt_lineage.py           # write docs/lineage.md
    python scripts/dbt_lineage.py --check   # fail if docs/lineage.md is outdated (CI)

A diagram in the repository is reviewable in pull requests and readable on GitHub
without running `dbt docs serve`.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "dbt" / "target" / "manifest.json"
OUTPUT = ROOT / "docs" / "lineage.md"
LAYERS = ("source", "staging", "intermediate", "marts", "exposure")


def _layer(node: dict) -> str:
    rtype = node["resource_type"]
    if rtype in ("source", "exposure"):
        return rtype
    if rtype == "seed":
        return "staging"  # seeds feed staging; drawn in the same column
    return node["fqn"][1] if len(node["fqn"]) > 2 else "marts"


def _label(node: dict) -> str:
    if node["resource_type"] == "source":
        return f"{node['source_name']}.{node['name']}"
    return node.get("label") or node["name"]


def render(manifest: dict) -> str:
    nodes = {
        uid: n
        for uid, n in {**manifest["nodes"], **manifest["sources"], **manifest["exposures"]}.items()
        if n["resource_type"] in ("model", "seed", "source", "exposure")
    }
    ids = {uid: f"n{i}" for i, uid in enumerate(sorted(nodes))}
    lines = ["flowchart LR"]
    for layer in LAYERS:
        members = sorted(uid for uid, n in nodes.items() if _layer(n) == layer)
        if not members:
            continue
        lines.append(f"    subgraph {layer}")
        for uid in members:
            n = nodes[uid]
            shape = (
                ("[(", ")]")
                if n["resource_type"] == "seed"
                else ("([", "])")
                if layer == "exposure"
                else ("[", "]")
            )
            lines.append(f'        {ids[uid]}{shape[0]}"{_label(n)}"{shape[1]}')
        lines.append("    end")
    edges = sorted(
        (ids[parent], ids[uid])
        for uid, n in nodes.items()
        for parent in n.get("depends_on", {}).get("nodes", [])
        if parent in ids
    )
    lines += [f"    {a} --> {b}" for a, b in edges]
    body = "\n".join(lines)
    return (
        "# dbt lineage\n\n"
        "> Generated by `scripts/dbt_lineage.py` from `dbt/target/manifest.json` — do not edit.\n"
        "> Cylinders are seeds; rounded boxes are exposures (consumers).\n\n"
        f"```mermaid\n{body}\n```\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is outdated")
    args = parser.parse_args()
    text = render(json.loads(MANIFEST.read_text(encoding="utf-8")))
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is outdated: run python scripts/dbt_lineage.py")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Run the analytical SQL files and publish their results as Markdown.

Each file in ``sql/analysis/`` starts with a header comment (the first comment block)
and contains one or more statements ending with ``;``. The comment lines right above a
statement describe it; the first one is used as its title, e.g. ``-- Q1: Overall KPIs``.

    python scripts/run_sql.py            # run all files, write reports/sql/<file>.md
    python scripts/run_sql.py --check    # only run them; fail on any error (CI)
    python scripts/run_sql.py 01         # only files whose name starts with "01"

Queries run on a **read-only** connection to the warehouse (``LF_DB_PATH``).
"""

from __future__ import annotations

import argparse
import os
import sys
from dataclasses import dataclass
from pathlib import Path

import duckdb
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SQL_DIR = ROOT / "sql" / "analysis"
OUT_DIR = ROOT / "reports" / "sql"
MAX_ROWS = 25


@dataclass
class Statement:
    title: str
    description: list[str]
    sql: str


def parse(text: str) -> tuple[list[str], list[Statement]]:
    """Split a file into its header comment and its statements."""
    lines = text.splitlines()
    header: list[str] = []
    i = 0
    while i < len(lines) and lines[i].startswith("--"):
        header.append(lines[i][2:].strip())
        i += 1
    statements: list[Statement] = []
    comments: list[str] = []
    body: list[str] = []
    for line in lines[i:]:
        stripped = line.strip()
        if not body and stripped.startswith("--"):
            comments.append(stripped[2:].strip())
            continue
        if not body and not stripped:
            continue
        body.append(line)
        if stripped.endswith(";"):
            title = comments[0] if comments else f"Statement {len(statements) + 1}"
            statements.append(Statement(title, comments[1:], "\n".join(body).rstrip(";\n ")))
            comments, body = [], []
    return header, statements


def _markdown_table(df: pd.DataFrame) -> str:
    shown = df.head(MAX_ROWS)

    def fmt(v: object, column: str) -> str:
        if v is None or (isinstance(v, float) and pd.isna(v)):
            return "∅"
        if "year" in column:  # 2025, not 2,025
            return str(int(v))
        if isinstance(v, float):
            return f"{v:,.4f}".rstrip("0").rstrip(".")
        if isinstance(v, int):
            return f"{v:,}"
        return str(v).replace("|", "\\|")

    lines = [
        "| " + " | ".join(shown.columns) + " |",
        "|" + "---|" * len(shown.columns),
    ]
    lines += [
        "| " + " | ".join(fmt(v, c) for v, c in zip(row, shown.columns, strict=True)) + " |"
        for row in shown.itertuples(index=False)
    ]
    if len(df) > MAX_ROWS:
        lines.append(f"\n_… {len(df) - MAX_ROWS} more rows not shown._")
    return "\n".join(lines)


def run_file(con: duckdb.DuckDBPyConnection, path: Path) -> str:
    header, statements = parse(path.read_text(encoding="utf-8"))
    out = [
        f"# {header[0] if header else path.stem}",
        "",
        f"> Results of [`sql/analysis/{path.name}`](../../sql/analysis/{path.name}), "
        "generated by `scripts/run_sql.py` on the seed-42 warehouse (50 000 leads).",
        "",
    ]
    out += [h for h in header[1:] if h] and ["\n".join(f"> {h}" for h in header[1:] if h), ""]
    for st in statements:
        result = con.execute(st.sql).df()
        out += [f"## {st.title}", ""]
        if st.description:
            out += [" ".join(st.description), ""]
        out += ["```sql", st.sql, "```", "", _markdown_table(result), ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description="Run sql/analysis/*.sql")
    parser.add_argument("prefix", nargs="?", default="", help="only files starting with this")
    parser.add_argument("--check", action="store_true", help="run only, write nothing")
    args = parser.parse_args()

    db = Path(os.environ.get("LF_DB_PATH", ROOT / "data" / "warehouse" / "lead_funnel.duckdb"))
    files = sorted(p for p in SQL_DIR.glob("*.sql") if p.name.startswith(args.prefix))
    con = duckdb.connect(str(db), read_only=True)
    con.execute("set TimeZone = 'UTC'")
    con.execute("set enable_progress_bar = false")
    try:
        for path in files:
            report = run_file(con, path)
            if not args.check:
                OUT_DIR.mkdir(parents=True, exist_ok=True)
                target = OUT_DIR / f"{path.stem}.md"
                target.write_text(report, encoding="utf-8", newline="\n")
                print(f"wrote {target.relative_to(ROOT)}")
            else:
                print(f"ok   {path.name}")
    finally:
        con.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
